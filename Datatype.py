# Integer
a = 10
print("Integer:", a)
print("Type:", type(a))

# Float
b = 10.5
print("\nFloat:", b)
print("Type:", type(b))

# Complex
c = 3 + 4j
print("\nComplex:", c)
print("Type:", type(c))

# String
name = "Mitali"
print("\nString:", name)
print("Type:", type(name))

# Boolean
is_student = True
print("\nBoolean:", is_student)
print("Type:", type(is_student))

# List (Ordered, Mutable)
fruits = ["Apple", "Banana", "Mango"]
print("\nList:", fruits)
print("Type:", type(fruits))

# Tuple (Ordered, Immutable)
numbers = (10, 20, 30)
print("\nTuple:", numbers)
print("Type:", type(numbers))

# Set (Unordered, No Duplicates)
colors = {"Red", "Green", "Blue"}
print("\nSet:", colors)
print("Type:", type(colors))

# Dictionary (Key-Value Pair)
student = {
    "Name": "Mitali",
    "Age": 20,
    "Branch": "CSE"
}
print("\nDictionary:", student)
print("Type:", type(student))

# None Type
x = None
print("\nNone:", x)
print("Type:", type(x))